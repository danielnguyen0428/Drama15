/**
 * Build a compact list of recently used character names (full names and given
 * names) so the next Story_Bible generation can avoid recycling them. Returns
 * an empty string when there is no history with character names yet, so the
 * caller can omit the block entirely.
 */
export function renderRecentCharacterNamesForPrompt(history: SeedHistoryEntry[], limit = 30): string {
  const fullNames = new Set<string>();
  const givenNames = new Set<string>();
  const middleNames = new Set<string>();

  for (const entry of history.slice(0, limit)) {
    if (!Array.isArray(entry.characterNames)) continue;
    for (const raw of entry.characterNames) {
      if (typeof raw !== 'string') continue;
      const name = raw.trim();
      if (!name) continue;
      fullNames.add(name);
      const parts = name.split(/\s+/).filter(Boolean);
      // Vietnamese full names are typically [Họ] [Tên đệm...] [Tên]. The given
      // name (last token) is the highest-collision risk, and the second-to-last
      // token is the typical "tên đệm" that LLMs default to (Minh, Thị, ...).
      const lastToken = parts[parts.length - 1];
      const secondLastToken = parts[parts.length - 2];
      if (lastToken !== undefined) givenNames.add(lastToken);
      if (secondLastToken !== undefined) middleNames.add(secondLastToken);
    }
  }

  if (fullNames.size === 0) return '';

  const payload = {
    recentFullNames: Array.from(fullNames),
    overusedGivenNames: Array.from(givenNames),
    overusedMiddleNames: Array.from(middleNames),
  };

  return [
    'Recent character names to avoid (DO NOT reuse any of these full names, given names, or middle-name tokens):',
    JSON.stringify(payload, null, 2),
  ].join('\n');
}

