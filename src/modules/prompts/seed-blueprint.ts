const FALLBACK_LINE_PRESET = "billionaire_rich_poor_romance";
const SEED_BLUEPRINT_BANKS = mergeFictionMeSeedSignals(BASE_SEED_BLUEPRINT_BANKS);

export function createSeedBlueprint(options: CreateSeedBlueprintOptions): SeedBlueprint {
  const random = options.random ?? Math.random;
  const bank = SEED_BLUEPRINT_BANKS[options.linePreset] ?? SEED_BLUEPRINT_BANKS[FALLBACK_LINE_PRESET];
  const recentHistory = options.history ?? [];
  const recentFingerprints = new Set(recentHistory.map((entry) => entry.fingerprint).filter(Boolean));
  const recentSkeletonFingerprints = new Set(
    recentHistory
      .map((entry) => (entry.blueprint ? createSeedSkeletonFingerprint(entry.blueprint) : ""))
      .filter(Boolean),
  );
  const recentRelationshipDynamics = new Set(recentHistory.map((entry) => entry.blueprint?.relationshipDynamic).filter(Boolean));
  const recentProtagonistAgencies = new Set(recentHistory.map((entry) => entry.blueprint?.protagonistAgency).filter(Boolean));
  const recentAntagonistWebs = new Set(recentHistory.map((entry) => entry.blueprint?.antagonistWeb).filter(Boolean));
  const recentRevealMechanisms = new Set(recentHistory.map((entry) => entry.blueprint?.revealMechanism).filter(Boolean));
  const recentEndingShapes = new Set(recentHistory.map((entry) => entry.blueprint?.endingShape).filter(Boolean));
  const maxAttempts = options.maxAttempts ?? DEFAULT_MAX_ATTEMPTS;
  let fallback: SeedBlueprint | null = null;
  let bestCandidate: { blueprint: SeedBlueprint; score: number } | null = null;

  for (let attempt = 0; attempt < maxAttempts; attempt += 1) {
    const blueprint = buildBlueprint(options.linePreset, bank, random, attempt);
    fallback ??= blueprint;
    const skeletonFingerprint = createSeedSkeletonFingerprint(blueprint);
    const score = scoreBlueprintNovelty(blueprint, {
      recentFingerprints,
      recentSkeletonFingerprints,
      recentRelationshipDynamics,
      recentProtagonistAgencies,
      recentAntagonistWebs,
      recentRevealMechanisms,
      recentEndingShapes,
    });
    if (!bestCandidate || score > bestCandidate.score) {
      bestCandidate = { blueprint, score };
    }

    if (
      !hasRecentFingerprintMatch(blueprint.fingerprint, recentFingerprints) &&
      !recentSkeletonFingerprints.has(skeletonFingerprint) &&
      !recentRelationshipDynamics.has(blueprint.relationshipDynamic) &&
      !recentProtagonistAgencies.has(blueprint.protagonistAgency) &&
      !recentRevealMechanisms.has(blueprint.revealMechanism) &&
      !recentEndingShapes.has(blueprint.endingShape)
    ) {
      return blueprint;
    }
  }

  return bestCandidate?.blueprint ?? fallback ?? buildBlueprint(options.linePreset, bank, random, 0);
}

