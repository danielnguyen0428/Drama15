function appendUnique(base: string[], additions: string[]) {
  return Array.from(new Set([...base, ...additions]));
}

function buildBlueprint(
  linePreset: string,
  bank: SeedBlueprintBank | undefined,
  random: () => number,
  attempt: number,
): SeedBlueprint {
  if (!bank) {
    throw new Error(`No seed blueprint bank configured for "${linePreset}".`);
  }

  const blueprintWithoutFingerprint = {
    linePreset,
    topicAnchor: pick(bank.topicAnchors, random, attempt, 0),
    motifFamily: pick(bank.motifFamilies, random, attempt, 1),
    socialPain: pick(bank.socialPains, random, attempt, 2),
    arena: pick(bank.arenas, random, attempt, 3),
    incitingHumiliation: pick(bank.incitingHumiliations, random, attempt, 4),
    hiddenLeverage: pick(bank.hiddenLeverages, random, attempt, 5),
    evidenceObject: pick(bank.evidenceObjects, random, attempt, 6),
    betrayerPressure: pick(bank.betrayerPressures, random, attempt, 7),
    statusForce: pick(bank.statusForces, random, attempt, 8),
    publicRevealVenue: pick(bank.publicRevealVenues, random, attempt, 9),
    freshnessAngle: pick(bank.freshnessAngles, random, attempt, 10),
    relationshipDynamic: pick(bank.relationshipDynamics, random, attempt, 11),
    protagonistAgency: pick(bank.protagonistAgencies, random, attempt, 12),
    antagonistWeb: pick(bank.antagonistWebs, random, attempt, 13),
    revealMechanism: pick(bank.revealMechanisms, random, attempt, 14),
    endingShape: pick(bank.endingShapes, random, attempt, 15),
  };

  return {
    ...blueprintWithoutFingerprint,
    fingerprint: createSeedFingerprint(blueprintWithoutFingerprint),
  };
}

function pick(values: string[], random: () => number, attempt: number, salt: number) {
  const baseIndex = Math.floor(clampRandom(random()) * values.length);
  const offset = attempt === 0 ? 0 : attempt + salt;
  return values[(baseIndex + offset) % values.length] ?? values[0] ?? "";
}

function clampRandom(value: number) {
  if (!Number.isFinite(value)) {
    return 0;
  }

  return Math.min(0.999_999, Math.max(0, value));
}

function createSeedFingerprint(value: Omit<SeedBlueprint, "fingerprint">) {
  return [
    value.linePreset,
    value.topicAnchor,
    value.motifFamily,
    value.socialPain,
    value.arena,
    value.hiddenLeverage,
    value.publicRevealVenue,
    value.relationshipDynamic,
    value.protagonistAgency,
    value.antagonistWeb,
    value.revealMechanism,
    value.endingShape,
  ]
    .map(normalizeFingerprintPart)
    .join("|");
}

function createSeedSkeletonFingerprint(value: Pick<
  SeedBlueprint,
  "linePreset" | "relationshipDynamic" | "protagonistAgency" | "antagonistWeb" | "revealMechanism" | "endingShape"
>) {
  return [
    value.linePreset,
    value.relationshipDynamic,
    value.protagonistAgency,
    value.antagonistWeb,
    value.revealMechanism,
    value.endingShape,
  ]
    .map(normalizeFingerprintPart)
    .join("|");
}

function scoreBlueprintNovelty(
  blueprint: SeedBlueprint,
  recent: {
    recentFingerprints: Set<string>;
    recentSkeletonFingerprints: Set<string>;
    recentRelationshipDynamics: Set<string | undefined>;
    recentProtagonistAgencies: Set<string | undefined>;
    recentAntagonistWebs: Set<string | undefined>;
    recentRevealMechanisms: Set<string | undefined>;
    recentEndingShapes: Set<string | undefined>;
  },
) {
  let score = 0;
  if (!hasRecentFingerprintMatch(blueprint.fingerprint, recent.recentFingerprints)) score += 10;
  if (!recent.recentSkeletonFingerprints.has(createSeedSkeletonFingerprint(blueprint))) score += 8;
  if (!recent.recentEndingShapes.has(blueprint.endingShape)) score += 5;
  if (!recent.recentRelationshipDynamics.has(blueprint.relationshipDynamic)) score += 4;
  if (!recent.recentRevealMechanisms.has(blueprint.revealMechanism)) score += 4;
  if (!recent.recentProtagonistAgencies.has(blueprint.protagonistAgency)) score += 3;
  if (!recent.recentAntagonistWebs.has(blueprint.antagonistWeb)) score += 2;
  return score;
}

function hasRecentFingerprintMatch(fingerprint: string, recentFingerprints: Set<string>) {
  if (recentFingerprints.has(fingerprint)) {
    return true;
  }

  for (const recentFingerprint of recentFingerprints) {
    if (recentFingerprint && fingerprint.startsWith(`${recentFingerprint}|`)) {
      return true;
    }
  }

  return false;
}

function normalizeFingerprintPart(value: string | null | undefined) {
  return (value ?? "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "");
}
